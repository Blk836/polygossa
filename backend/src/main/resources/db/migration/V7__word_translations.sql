-- Word meanings in the learner's own language (word-translations.feature).

-- A saved word's own-language meaning, apart from its definition, and the native language it is in. Words saved
-- before this have none and count for nothing.
alter table vocabulary_entries add column if not exists meaning varchar(200);
alter table vocabulary_entries add column if not exists meaning_language varchar(255);

-- Community meanings: what learners of a language with one native language saved for a word.
create index if not exists idx_vocab_community_meaning
    on vocabulary_entries (language, term, meaning_language) where meaning is not null;

-- Machine translations, asked once per word and language pair and kept for everyone. A null translation means the
-- answer was no use (the word itself), so it isn't asked again.
create table if not exists machine_translations (
    id bigint generated by default as identity,
    source_language varchar(255) not null,
    target_language varchar(255) not null,
    term varchar(200) not null,
    translation varchar(500),
    created_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_machine_translation unique (source_language, target_language, term)
);

-- Characters sent for machine translation per month (UTC, "2026-10"), against the monthly cap.
create table if not exists translation_usage (
    month varchar(7) not null,
    characters bigint not null,
    primary key (month)
);
