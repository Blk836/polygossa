create table if not exists sentence_meanings (
    id bigint generated by default as identity,
    source_language varchar(255) not null check ((source_language in ('EN','ES','FR','DE','IT','PT','JA','ZH','KO'))),
    target_language varchar(255) not null
        check ((target_language in ('EN','ES','FR','DE','IT','PT','NL','PL','SV','TR','VI','ID','RU','UK','AR','HI','JA','ZH','KO'))),
    term varchar(200) not null,
    context_hash varchar(64) not null,
    meaning varchar(100) not null,
    created_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_sentence_meaning unique (source_language, target_language, term, context_hash)
);
