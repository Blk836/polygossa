create table if not exists lookup_counters (
    id bigint generated by default as identity,
    day date not null,
    source_language varchar(255) not null check ((source_language in ('EN','ES','FR','DE','IT','PT','JA','ZH','KO'))),
    target_language varchar(255) not null
        check ((target_language in ('EN','ES','FR','DE','IT','PT','NL','PL','SV','TR','VI','ID','RU','UK','AR','HI','JA','ZH','KO'))),
    layer varchar(255) not null
        check ((layer in ('AI_STORED','AI_NEW','COMMUNITY','MACHINE_STORED','MACHINE_NEW','NONE'))),
    lookups bigint not null,
    translate_calls bigint not null,
    translate_characters bigint not null,
    translate_failures bigint not null,
    translate_capped bigint not null,
    ai_calls bigint not null,
    ai_tokens_in bigint not null,
    ai_tokens_out bigint not null,
    ai_failures bigint not null,
    primary key (id),
    constraint uk_lookup_counter unique (day, source_language, target_language, layer)
);
