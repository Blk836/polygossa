package app.lector.video;

import app.lector.text.SubtitleParser.Cue;
import app.lector.text.SubtitleParser.WordMark;
import app.lector.token.Language;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.jsoup.Jsoup;
import org.jsoup.nodes.Document;
import org.jsoup.nodes.Element;
import org.jsoup.nodes.Node;
import org.jsoup.nodes.TextNode;
import org.jsoup.parser.Parser;
import tools.jackson.core.JacksonException;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;
import tools.jackson.databind.json.JsonMapper;

public final class CaptionParser {

    public record Track(String baseUrl, String languageCode, boolean autoGenerated) {}

    public record PlayerInfo(Integer durationSeconds, List<Track> tracks, String youtubeCategory) {

        public PlayerInfo(Integer durationSeconds, List<Track> tracks) {
            this(durationSeconds, tracks, null);
        }

        PlayerInfo withCategory(String category) {
            return new PlayerInfo(durationSeconds, tracks, category);
        }
    }

    static final PlayerInfo NONE = new PlayerInfo(null, List.of());

    private static final ObjectMapper JSON = JsonMapper.builder().build();
    private static final Pattern API_KEY = Pattern.compile("\"INNERTUBE_API_KEY\"\\s*:\\s*\"([A-Za-z0-9_-]+)\"");

    private static final Pattern CATEGORY = Pattern.compile("\"category\"\\s*:\\s*\"([^\"]+)\"");

    private CaptionParser() {}

    public static Optional<String> youtubeCategory(String watchPage) {
        if (watchPage == null) {
            return Optional.empty();
        }
        Matcher m = CATEGORY.matcher(watchPage);
        return m.find() ? Optional.of(m.group(1).replace("\\u0026", "&")) : Optional.empty();
    }

    public static Optional<String> apiKey(String watchPage) {
        if (watchPage == null) {
            return Optional.empty();
        }
        Matcher m = API_KEY.matcher(watchPage);
        return m.find() ? Optional.of(m.group(1)) : Optional.empty();
    }

    public static PlayerInfo parsePlayer(String json) {
        if (json == null) {
            return NONE;
        }
        JsonNode root;
        try {
            root = JSON.readTree(json);
        } catch (JacksonException e) {
            return NONE;
        }
        Integer duration = positiveInt(root.path("videoDetails").path("lengthSeconds").asString(""));
        boolean playable = "OK".equals(root.path("playabilityStatus").path("status").asString(""));
        List<Track> tracks = new ArrayList<>();
        JsonNode list = root.path("captions").path("playerCaptionsTracklistRenderer").path("captionTracks");
        for (JsonNode t : playable ? list : JSON.createArrayNode()) {
            String url = t.path("baseUrl").asString("");
            String lang = t.path("languageCode").asString("");
            if (!url.isEmpty() && !lang.isEmpty()) {
                tracks.add(new Track(url, lang, "asr".equals(t.path("kind").asString(""))));
            }
        }
        return new PlayerInfo(duration, List.copyOf(tracks));
    }

    public static Optional<Track> pickTrack(List<Track> tracks, Language language) {
        String code = language.code();
        return tracks.stream()
                .filter(t -> matches(t, code))
                .min(Comparator.comparingInt(t -> (t.autoGenerated() ? 0 : 2) + (isExact(t, code) ? 0 : 1)));
    }

    public static String srv3Url(String baseUrl) {
        int q = baseUrl.indexOf('?');
        List<String> params = new ArrayList<>();
        if (q >= 0) {
            for (String p : baseUrl.substring(q + 1).split("&")) {
                if (!p.isEmpty() && !p.startsWith("fmt=")) {
                    params.add(p);
                }
            }
        }
        params.add("fmt=srv3");
        return (q >= 0 ? baseUrl.substring(0, q) : baseUrl) + "?" + String.join("&", params);
    }

    public static List<Cue> parseTimedText(String xml) {
        if (xml == null || xml.isBlank()) {
            return List.of();
        }
        Document doc = Jsoup.parse(xml, "", Parser.xmlParser());
        List<Cue> out = new ArrayList<>();
        for (Element p : doc.select("p[t]")) {
            add(out, p, p.attr("t"), p.attr("d"), 1);
        }
        for (Element t : doc.select("text[start]")) {
            add(out, t, t.attr("start"), t.attr("dur"), 1000);
        }
        return out;
    }

    private static void add(List<Cue> out, Element el, String start, String duration, int scale) {
        Long startMs = millis(start, scale);
        if (startMs == null) {
            return;
        }
        Line line = el.selectFirst("s") == null ? new Line(decode(el.text()).strip(), List.of()) : words(el, startMs);
        if (line.text().isEmpty()) {
            return;
        }
        Long durationMs = millis(duration, scale);
        out.add(new Cue(startMs, startMs + (durationMs == null ? 0 : durationMs), line.text(), 0, 0, line.marks()));
    }

    private record Line(String text, List<WordMark> marks) {}

    private static Line words(Element p, long startMs) {
        StringBuilder text = new StringBuilder();
        List<WordMark> marks = new ArrayList<>();
        for (Node node : p.childNodes()) {
            String piece = collapse(text, rawText(node));
            int lead = piece.length() - piece.stripLeading().length();
            if (node instanceof Element s && "s".equals(s.normalName()) && lead < piece.length()) {
                Long offset = millis(s.attr("t"), 1);
                marks.add(new WordMark(text.length() + lead, startMs + (offset == null ? 0 : offset)));
            }
            text.append(piece);
        }
        return new Line(text.toString().stripTrailing(), marks);
    }

    private static String rawText(Node node) {
        if (node instanceof Element e) {
            return e.wholeText();
        }
        return node instanceof TextNode t ? t.getWholeText() : "";
    }

    private static String collapse(CharSequence before, String raw) {
        String piece = decode(raw).replaceAll("\\s+", " ");
        boolean spaceBefore = before.isEmpty() || before.charAt(before.length() - 1) == ' ';
        return spaceBefore && piece.startsWith(" ") ? piece.substring(1) : piece;
    }

    private static String decode(String text) {
        return Parser.unescapeEntities(text, false);
    }

    private static Long millis(String value, int scale) {
        try {
            return Math.round(Double.parseDouble(value) * scale);
        } catch (NumberFormatException e) {
            return null;
        }
    }

    private static Integer positiveInt(String value) {
        try {
            int n = Integer.parseInt(value);
            return n > 0 ? n : null;
        } catch (NumberFormatException e) {
            return null;
        }
    }

    private static boolean isExact(Track t, String code) {
        return t.languageCode().equalsIgnoreCase(code);
    }

    private static boolean matches(Track t, String code) {
        return isExact(t, code) || t.languageCode().toLowerCase(Locale.ROOT).startsWith(code + "-");
    }
}
