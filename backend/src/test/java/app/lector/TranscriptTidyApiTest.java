    private void video(String language, String srv3, boolean automatic) {
        YOUTUBE.add(VIDEO, YouTubeStub.Video.withCaptions("Cocina", 60, language, srv3));
        if (automatic) {
            YOUTUBE.markAutoGenerated(VIDEO);
        }
    }

    private void video(String srv3, boolean automatic) {
        video("es", srv3, automatic);
    }

    private JsonNode importVideo(String language) throws Exception {
        long id = api.send(multipart("/api/texts/import-youtube").param("url", "https://youtu.be/" + VIDEO)
                .param("language", language), user, 201).get("id").asLong();
        return api.get(user, "/api/texts/" + id, 200);
    }

    private JsonNode importVideo() throws Exception {
        return importVideo("es");
    }

    private static String content(JsonNode detail) {
        StringBuilder out = new StringBuilder();
        detail.get("tokens").forEach(t -> out.append(t.get("text").asString()));
        return out.toString();
    }

    private record Timed(String word, long s, long e) {}

    private static List<Timed> wordTimes(JsonNode detail) {
        List<String> words = new ArrayList<>();
        detail.get("tokens").forEach(t -> words.add(t.get("text").asString().toLowerCase(Locale.ROOT)));
        List<Timed> out = new ArrayList<>();
        for (JsonNode timing : detail.get("video").get("timings")) {
            out.add(new Timed(words.get(timing.get("i").asInt()), timing.get("s").asLong(), timing.get("e").asLong()));
        }
        return out;
    }

    private static long tokenIndex(JsonNode detail, String word) {
        for (JsonNode t : detail.get("tokens")) {
            if (t.get("text").asString().equals(word)) {
                return t.get("index").asLong();
            }
        }
        throw new AssertionError("no token " + word);
    }

    private static List<String> tidyRequests() {
        return AI.requests().stream().filter(r -> r.contains(TIDY)).toList();
    }

    private static String lines(String... lines) {
        return "{\"lines\":[" + Arrays.stream(lines).map(l -> "\"" + l + "\"")
                .collect(Collectors.joining(",")) + "],\"paragraphStarts\":[]}";
    }

    private JsonNode untidiedImport() throws Exception {
        AI.setFailing(true);
        JsonNode detail = importVideo();
        AI.reset();
        AI.reply("{\"category\":\"food\"}");
        jobUsage.deleteAll();
        return detail;
    }

    @Test
    void anAutomaticUnpunctuatedTranscriptIsTidiedIntoRunningSentences() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, lines("¡Hola, amigos!", "Hoy cocinamos arroz."));
        JsonNode detail = importVideo();
        assertThat(content(detail)).isEqualTo("¡Hola, amigos! Hoy cocinamos arroz.");
        assertThat(tidyRequests()).hasSize(1);
        assertThat(tidyRequests().getFirst()).contains("hola amigos").contains("hoy cocinamos arroz");
    }

    @Test
    void everyWordLightsUpAtExactlyTheSameMomentAsUntidied() throws Exception {
        video("fr", YouTubeStub.srv3Words(
                "0|3000|bonjour@0 à@400 tous@700 et@1100 bienvenue@1500",
                "3000|3000|euh@3000 le@3600 printemps@3900 est@4500 arrivé@5000",
                "6000|2000|il@6000 fait@6400 beau@6900"), true);
        AI.setFailing(true);
        List<Timed> before = wordTimes(importVideo("fr"));
        AI.reset();
        AI.reply("{\"category\":\"food\"}");
        AI.replyWhen(TIDY, lines("Bonjour à tous et bienvenue !", "Le printemps est arrivé :", "il fait beau."));

        JsonNode detail = importVideo("fr");

        assertThat(content(detail)).isEqualTo("Bonjour à tous et bienvenue ! euh Le printemps est arrivé : il fait beau.");
        List<Timed> after = wordTimes(detail);
        assertThat(after).hasSize(13);
        assertThat(after).isEqualTo(before);
        assertThat(after.get(5)).isEqualTo(new Timed("euh", 3000, 3600));
        assertThat(after.get(6).s()).isEqualTo(3600);
    }

    @Test
    void paragraphBreaksGoWhereTheAiSuggests() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, "{\"lines\":[\"¡Hola, amigos!\",\"Hoy cocinamos arroz.\"],\"paragraphStarts\":[1]}");
        assertThat(content(importVideo())).isEqualTo("¡Hola, amigos!\nHoy cocinamos arroz.");
    }

    @Test
    void aLineWhoseWordsChangedKeepsItsOriginalTextAndTheOthersAreTidied() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, lines("¡Hola, amigas!", "Hoy cocinamos arroz."));
        JsonNode detail = importVideo();
        assertThat(content(detail)).isEqualTo("hola amigos Hoy cocinamos arroz.");
        assertThat(detail.get("video").get("timings")).hasSize(5);
    }

    @Test
    void aReplyWithTheWrongNumberOfLinesKeepsThePartAsToday() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, lines("¡Hola, amigos! Hoy cocinamos arroz."));
        assertThat(content(importVideo())).isEqualTo("hola amigos\nhoy cocinamos arroz");
    }

    @Test
    void aFailingAiImportsAsToday() throws Exception {
        video(BARE, true);
        AI.setFailing(true);
        JsonNode detail = importVideo();
        assertThat(content(detail)).isEqualTo("hola amigos\nhoy cocinamos arroz");
        assertThat(wordTimes(detail).get(2).s()).isEqualTo(2000);
    }

    @Test
    void anUnreadableAnswerImportsAsToday() throws Exception {
        video(BARE, true);
        AI.replyRaw("Sure! Here it is: Hola, amigos.");
        assertThat(content(importVideo())).isEqualTo("hola amigos\nhoy cocinamos arroz");
    }

    @Test
    void eachCallHasAnOutputCapOfAboutTwiceThePartSent() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, lines("¡Hola, amigos!", "Hoy cocinamos arroz."));
        importVideo();
        JsonNode request = json.readTree(tidyRequests().getFirst());
        int sent = request.get("messages").get(1).get("content").asString().length();
        int cap = request.get("max_completion_tokens").asInt();
        assertThat(cap).isGreaterThanOrEqualTo(sent / 4).isLessThanOrEqualTo(sent / 2 + 300);
    }

    @Test
    void aReplyCutOffAtTheCapKeepsThePartAsToday() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, lines("¡Hola, amigos!", "Hoy cocinamos arroz."));
        AI.finishReason("length");
        assertThat(content(importVideo())).isEqualTo("hola amigos\nhoy cocinamos arroz");
    }

    @Test
    void humanMadeCaptionsAreNotSentAndLookAsToday() throws Exception {
        video(BARE, false);
        assertThat(content(importVideo())).isEqualTo("hola amigos\nhoy cocinamos arroz");
        assertThat(tidyRequests()).isEmpty();
    }

    @Test
    void automaticCaptionsThatArePunctuatedRunOnWithoutAi() throws Exception {
        video(YouTubeStub.srv3("0|2000|Hola amigos, hoy", "2000|2000|cocinamos arroz."), true);
        JsonNode detail = importVideo();
        assertThat(tidyRequests()).isEmpty();
        assertThat(content(detail)).isEqualTo("Hola amigos, hoy cocinamos arroz.");
        assertThat(wordTimes(detail).get(3).s()).isEqualTo(2000);
    }

    @Test
    void anUploadedSubtitleFileIsNotSent() throws Exception {
        video(BARE, true);
        var srt = new MockMultipartFile("file", "x.srt", "text/plain",
                "1\n00:00:01,000 --> 00:00:03,000\nhola amigos\n".getBytes());
        api.send(multipart("/api/texts/import-youtube").file(srt).param("url", "https://youtu.be/" + VIDEO)
                .param("language", "es"), user, 201);
        assertThat(tidyRequests()).isEmpty();
    }

    @Test
    void aPastedTranscriptIsNotSent() throws Exception {
        video(BARE, true);
        api.send(multipart("/api/texts/import-youtube").param("url", "https://youtu.be/" + VIDEO)
                .param("language", "es").param("transcript", "hola amigos hoy cocinamos arroz"), user, 201);
        assertThat(tidyRequests()).isEmpty();
    }

    @Test
    void onceTheDailySystemCeilingIsReachedNothingIsSent() throws Exception {
        video(BARE, true);
        jobUsage.add(spending.today(), AiJob.TOPIC_TAGS.name(), 0, 0, 100_000);
        AI.replyWhen(TIDY, lines("¡Hola, amigos!", "Hoy cocinamos arroz."));
        assertThat(content(importVideo())).isEqualTo("hola amigos\nhoy cocinamos arroz");
        assertThat(tidyRequests()).isEmpty();
    }

    @Test
    void tidyingIsCountedAsItsOwnJobButNotAgainstTheAllowance() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, lines("¡Hola, amigos!", "Hoy cocinamos arroz."));
        AI.usage(120, 40);
        assertThat(content(importVideo())).isEqualTo("¡Hola, amigos! Hoy cocinamos arroz.");
        assertThat(allowance.findAll()).isEmpty();
        assertThat(jobUsage.findAll()).filteredOn(u -> u.getJob().equals(AiJob.TRANSCRIPT_TIDY.name()))
                .singleElement()
                .satisfies(u -> {
                    assertThat(u.getCalls()).isEqualTo(1);
                    assertThat(u.getTokensIn()).isEqualTo(120);
                    assertThat(u.getTokensOut()).isEqualTo(40);
                });
        assertThat(AiJob.TRANSCRIPT_TIDY.system()).isTrue();
    }

    private static String cueText(String marker) {
        return "palabra ".repeat(149) + marker;
    }

    private static String tidied(String marker) {
        return "Palabra " + "palabra ".repeat(148) + marker + ".";
    }

    @Test
    void aLongTranscriptGoesInPartsAndComesBackInOrder() throws Exception {
        List<String> markers = List.of("alfa", "bravo", "charlie", "delta", "echo", "foxtrot");
        List<String> timed = new ArrayList<>();
        IntStream.range(0, markers.size())
                .forEach(i -> timed.add(i * 5000 + "|5000|" + cueText(markers.get(i))));
        video(YouTubeStub.srv3(timed.toArray(String[]::new)), true);
        AI.replyWhen("alfa", lines(tidied("alfa"), tidied("bravo")));
        AI.replyWhen("charlie", lines(tidied("charlie")));
        AI.replyWhen("echo", lines(tidied("echo"), tidied("foxtrot")));
        String text = content(importVideo());
        assertThat(tidyRequests()).hasSize(3);
        assertThat(tidyRequests()).allSatisfy(r -> assertThat(r.split("palabra", -1).length - 1).isLessThanOrEqualTo(400));
        assertThat(text).isEqualTo(tidied("alfa") + " " + tidied("bravo") + "\n" + cueText("charlie") + "\n"
                + cueText("delta") + "\n" + tidied("echo") + " " + tidied("foxtrot"));
    }

    @Test
    void nothingRunsOverTheLibraryWhenTheServerStarts() {
        assertThat(context.getBeansOfType(ApplicationRunner.class).values())
                .noneMatch(runner -> runner.getClass().getName().startsWith("app.lector.video."));
    }

    private String admin() throws Exception {
        String body = "{\"email\":\"" + AdminApiTest.ADMIN + "\",\"password\":\"password123\"}";
        var signup = mvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders
                .post("/api/auth/signup").contentType(org.springframework.http.MediaType.APPLICATION_JSON).content(body))
                .andReturn().getResponse();
        String reply = signup.getStatus() == 201 ? signup.getContentAsString()
                : mvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders
                .post("/api/auth/login").contentType(org.springframework.http.MediaType.APPLICATION_JSON).content(body))
                .andReturn().getResponse().getContentAsString();
        return "Bearer " + json.readTree(reply).get("token").asString();
    }

    @Test
    void anAdminCanTidyOneImportedVideoAndReadersKeepTheirPlaceAndTiming() throws Exception {
        video(BARE, true);
        JsonNode old = untidiedImport();
        long id = old.get("text").get("id").asLong();
        api.post(user, "/api/texts/" + id + "/progress", "{\"position\":" + tokenIndex(old, "hoy") + "}", 200);
        AI.replyWhen(TIDY, lines("¡Hola, amigos!", "Hoy cocinamos arroz."));

        JsonNode report = api.post(admin(), "/api/admin/texts/" + id + "/tidy-transcript", "{}", 200);

        assertThat(report.get("lines").asInt()).isEqualTo(2);
        assertThat(report.get("tidiedLines").asInt()).isEqualTo(2);
        JsonNode detail = api.get(user, "/api/texts/" + id, 200);
        assertThat(content(detail)).isEqualTo("¡Hola, amigos! Hoy cocinamos arroz.");
        assertThat(wordTimes(detail)).isEqualTo(wordTimes(old));
        assertThat(detail.get("text").get("progress").get("position").asLong()).isEqualTo(tokenIndex(detail, "Hoy"));
        assertThat(detail.get("text").get("wordCount").asInt()).isEqualTo(5);
        assertThat(tidyRequests()).hasSize(1);
    }

    @Test
    void onlyAdminsCanTidyAnImportedVideo() throws Exception {
        video(BARE, true);
        long id = untidiedImport().get("text").get("id").asLong();
        api.post(user, "/api/admin/texts/" + id + "/tidy-transcript", "{}", 403);
        assertThat(tidyRequests()).isEmpty();
    }

    @Test
    void aTextWithoutCaptionsCannotBeTidied() throws Exception {
        long id = api.post(user, "/api/texts", "{\"title\":\"t\",\"language\":\"ES\",\"content\":\"hola amigos\"}", 201)
                .get("id").asLong();
        api.post(admin(), "/api/admin/texts/" + id + "/tidy-transcript", "{}", 400);
        api.post(admin(), "/api/admin/texts/999999999/tidy-transcript", "{}", 404);
    }
