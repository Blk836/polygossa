@SpringBootTest(properties = {
        "test.database=transcripttidy",
        "app.seed-samples=false",
        "app.openai.api-key=test-key",
        "app.openai.timeout=2s",
        "app.openai.daily-limit=0"
})
@AutoConfigureMockMvc
class TranscriptTidyApiTest {

    private static final String VIDEO = "dQw4w9WgXcQ";
    private static final String TIDY = "Restore punctuation";
    private static final OpenAiStub AI = ImportCategoryApiTest.start(OpenAiStub::new);
    private static final YouTubeStub YOUTUBE = ImportCategoryApiTest.start(YouTubeStub::new);

    private static final String BARE = YouTubeStub.srv3("0|2000|hola amigos", "2000|2000|hoy cocinamos arroz");

    @DynamicPropertySource
    static void stubs(DynamicPropertyRegistry registry) {
        registry.add("app.openai.base-url", AI::baseUrl);
        registry.add("app.youtube.base-url", YOUTUBE::baseUrl);
    }

    @AfterAll
    static void stop() {
        AI.close();
        YOUTUBE.close();
    }

    @Autowired
    MockMvc mvc;

    @Autowired
    ObjectMapper json;

    @Autowired
    AiUsageRepository usage;

    @Autowired
    TextRepository texts;

    @Autowired
    TransactionTemplate tx;

    @Autowired
    TranscriptBackfill backfill;

    TestApi api;
    String user;

    @BeforeEach
    void setUp() throws Exception {
        AI.reset();
        AI.reply("{\"category\":\"food\"}");
        YOUTUBE.reset();
        api = new TestApi(mvc, json);
        user = api.signupPro();
    }

    private void video(String srv3, boolean automatic) {
        YOUTUBE.add(VIDEO, YouTubeStub.Video.withCaptions("Cocina", 60, "es", srv3));
        if (automatic) {
            YOUTUBE.markAutoGenerated(VIDEO);
        }
    }

    private JsonNode importVideo() throws Exception {
        long id = api.send(multipart("/api/texts/import-youtube").param("url", "https://youtu.be/" + VIDEO)
                .param("language", "es"), user, 201).get("id").asLong();
        return api.get(user, "/api/texts/" + id, 200);
    }

    private static String content(JsonNode detail) {
        StringBuilder out = new StringBuilder();
        detail.get("tokens").forEach(t -> out.append(t.get("text").asString()));
        return out.toString();
    }

    private static long startOf(JsonNode detail, String word) {
        int index = -1;
        for (JsonNode t : detail.get("tokens")) {
            if (t.get("text").asString().equals(word)) {
                index = t.get("index").asInt();
            }
        }
        for (JsonNode timing : detail.get("video").get("timings")) {
            if (timing.get("i").asInt() == index) {
                return timing.get("s").asLong();
            }
        }
        throw new AssertionError("no timing for " + word);
    }

    private static List<String> tidyRequests() {
        return AI.requests().stream().filter(r -> r.contains(TIDY)).toList();
    }

    private static String lines(String... lines) {
        return "{\"lines\":[" + java.util.Arrays.stream(lines).map(l -> "\"" + l + "\"")
                .collect(Collectors.joining(",")) + "],\"paragraphStarts\":[]}";
    }

    @Test
    void anAutomaticUnpunctuatedTranscriptIsTidiedAndKeepsItsTiming() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, lines("¡Hola, amigos!", "Hoy cocinamos arroz."));
        JsonNode detail = importVideo();
        assertThat(content(detail)).isEqualTo("¡Hola, amigos! Hoy cocinamos arroz.");
        assertThat(startOf(detail, "Hola")).isZero();
        assertThat(startOf(detail, "Hoy")).isEqualTo(2000);
        assertThat(detail.get("video").get("timings").size()).isEqualTo(5);
        assertThat(tidyRequests()).hasSize(1);
        assertThat(tidyRequests().getFirst()).contains("hola amigos").contains("hoy cocinamos arroz");
    }

    @Test
    void paragraphBreaksGoWhereTheAiSuggests() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, "{\"lines\":[\"¡Hola, amigos!\",\"Hoy cocinamos arroz.\"],\"paragraphStarts\":[1]}");
        assertThat(content(importVideo())).isEqualTo("¡Hola, amigos!\nHoy cocinamos arroz.");
    }

    @Test
    void aReplyThatChangesAWordKeepsTheOriginal() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, lines("¡Hola, amigas!", "Hoy cocinamos arroz."));
        assertThat(content(importVideo())).isEqualTo("hola amigos\nhoy cocinamos arroz");
    }

    @Test
    void aFailingAiImportsAsToday() throws Exception {
        video(BARE, true);
        AI.setFailing(true);
        JsonNode detail = importVideo();
        assertThat(content(detail)).isEqualTo("hola amigos\nhoy cocinamos arroz");
        assertThat(startOf(detail, "hoy")).isEqualTo(2000);
    }

    @Test
    void anUnreadableAnswerImportsAsToday() throws Exception {
        video(BARE, true);
        AI.replyRaw("Sure! Here it is: Hola, amigos.");
        assertThat(content(importVideo())).isEqualTo("hola amigos\nhoy cocinamos arroz");
    }

    @Test
    void humanMadeCaptionsAreNotSent() throws Exception {
        video(BARE, false);
        assertThat(content(importVideo())).isEqualTo("hola amigos\nhoy cocinamos arroz");
        assertThat(tidyRequests()).isEmpty();
    }

    @Test
    void automaticCaptionsThatArePunctuatedAreNotSent() throws Exception {
        video(YouTubeStub.srv3("0|2000|Hola amigos.", "2000|2000|Hoy cocinamos arroz."), true);
        importVideo();
        assertThat(tidyRequests()).isEmpty();
    }

    @Test
    void anUploadedSubtitleFileIsNotSent() throws Exception {
        video(BARE, true);
        var srt = new MockMultipartFile("file", "x.srt", "text/plain",
                "1\n00:00:01,000 --> 00:00:03,000\nhola amigos\n".getBytes());
        api.send(multipart("/api/texts/import-youtube").file(srt).param("url", "https://youtu.be/" + VIDEO)
                .param("language", "es"), user, 201);
        assertThat(tidyRequests()).isEmpty();
    }

    private static String cueText(String marker) {
        return "palabra ".repeat(149) + marker;
    }

    private static String tidied(String marker) {
        return "Palabra " + "palabra ".repeat(148) + marker + ".";
    }

    @Test
    void aLongTranscriptGoesInPartsAndComesBackInOrder() throws Exception {
        List<String> markers = List.of("alfa", "bravo", "charlie", "delta", "echo", "foxtrot");
        List<String> timed = new ArrayList<>();
        IntStream.range(0, markers.size())
                .forEach(i -> timed.add(i * 5000 + "|5000|" + cueText(markers.get(i))));
        video(YouTubeStub.srv3(timed.toArray(String[]::new)), true);
        AI.replyWhen("alfa", lines(tidied("alfa"), tidied("bravo")));
        AI.replyWhen("charlie", lines(tidied("charlie"), "Palabra " + cueText("cambio")));
        AI.replyWhen("echo", lines(tidied("echo"), tidied("foxtrot")));
        String text = content(importVideo());
        assertThat(tidyRequests()).hasSize(3);
        assertThat(tidyRequests()).allSatisfy(r -> assertThat(r.split("palabra", -1).length - 1).isLessThanOrEqualTo(400));
        assertThat(text).isEqualTo(tidied("alfa") + " " + tidied("bravo") + "\n" + cueText("charlie") + "\n"
                + cueText("delta") + "\n" + tidied("echo") + " " + tidied("foxtrot"));
    }

    private long untidiedVideo() throws Exception {
        video(BARE, true);
        AI.setFailing(true);
        long id = importVideo().get("text").get("id").asLong();
        AI.reset();
        AI.reply("{\"category\":\"food\"}");
        tx.executeWithoutResult(s -> texts.findById(id).orElseThrow().setTranscriptChecked(false));
        return id;
    }

    private boolean checked(long id) {
        return Boolean.TRUE.equals(tx.execute(s -> texts.findById(id).orElseThrow().isTranscriptChecked()));
    }

    private long tokenIndex(JsonNode detail, String word) {
        for (JsonNode t : detail.get("tokens")) {
            if (t.get("text").asString().equals(word)) {
                return t.get("index").asLong();
            }
        }
        throw new AssertionError("no token " + word);
    }

    @Test
    void anExistingUntidiedVideoIsTidiedOnceAndTheReaderKeepsTheirPlace() throws Exception {
        long id = untidiedVideo();
        JsonNode old = api.get(user, "/api/texts/" + id, 200);
        api.post(user, "/api/texts/" + id + "/progress", "{\"position\":" + tokenIndex(old, "hoy") + "}", 200);
        AI.replyWhen(TIDY, lines("¡Hola, amigos!", "Hoy cocinamos arroz."));

        backfill.backfill();

        JsonNode detail = api.get(user, "/api/texts/" + id, 200);
        assertThat(content(detail)).isEqualTo("¡Hola, amigos! Hoy cocinamos arroz.");
        assertThat(startOf(detail, "Hoy")).isEqualTo(2000);
        assertThat(detail.get("text").get("progress").get("position").asLong()).isEqualTo(tokenIndex(detail, "Hoy"));
        assertThat(detail.get("text").get("wordCount").asInt()).isEqualTo(5);
        assertThat(tidyRequests()).hasSize(1);

        backfill.backfill();
        assertThat(tidyRequests()).hasSize(1);
    }

    @Test
    void anExistingVideoTheAiCannotTidyIsLeftAndNotAskedAgain() throws Exception {
        long id = untidiedVideo();
        AI.replyWhen(TIDY, lines("¡Hola, amigas!", "Hoy cocinamos arroz."));
        backfill.backfill();
        backfill.backfill();
        assertThat(content(api.get(user, "/api/texts/" + id, 200))).isEqualTo("hola amigos\nhoy cocinamos arroz");
        assertThat(tidyRequests()).hasSize(1);
    }

    @Test
    void anExistingVideoWithPunctuationIsNotSent() throws Exception {
        video(YouTubeStub.srv3("0|2000|Hola amigos.", "2000|2000|Hoy cocinamos arroz."), true);
        long id = importVideo().get("text").get("id").asLong();
        tx.executeWithoutResult(s -> texts.findById(id).orElseThrow().setTranscriptChecked(false));
        backfill.backfill();
        assertThat(tidyRequests()).isEmpty();
        assertThat(checked(id)).isTrue();
    }

    @Test
    void newImportsAreNotLeftForTheBackfill() throws Exception {
        video(BARE, true);
        AI.setFailing(true);
        long id = importVideo().get("text").get("id").asLong();
        assertThat(checked(id)).isTrue();
    }

    @Test
    void tidyingDoesNotUseTheAllowance() throws Exception {
        video(BARE, true);
        AI.replyWhen(TIDY, lines("¡Hola, amigos!", "Hoy cocinamos arroz."));
        assertThat(content(importVideo())).isEqualTo("¡Hola, amigos! Hoy cocinamos arroz.");
        assertThat(usage.findAll()).isEmpty();
    }
}
